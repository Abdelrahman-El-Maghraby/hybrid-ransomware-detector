needs_7zip = pytest.mark.skipif(mp.sevenzip_tool() is None, reason="7-Zip not installed")
MARKER = b"S01-MARKER benign test content\n"


def _tar(entries):
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w") as t:
        for name, kind, data in entries:
            info = tarfile.TarInfo(name)
            if kind == "link":
                info.type, info.linkname = tarfile.SYMTYPE, data
                t.addfile(info)
            else:
                info.size = len(data)
                t.addfile(info, io.BytesIO(data))
    return buf.getvalue()


def _image(path, entries):
    return build_dmg(path, partition=_tar(entries))


def _markers_outside(tmp_path, sandbox_roots):
    """Every file holding MARKER under tmp_path and the temp folder's top level,
    except inside the extractor's sandboxes."""
    import tempfile
    hits = []
    for base in {tmp_path, Path(tempfile.gettempdir())}:
        files = base.rglob("*") if base == tmp_path else base.glob("*")
        for f in files:
            try:
                if f.is_file() and not f.is_symlink() and MARKER in f.read_bytes():
                    if not any(str(f).startswith(str(r)) for r in sandbox_roots):
                        hits.append(f)
            except OSError:
                continue
    return [h for h in hits if h.suffix != ".dmg"]


@pytest.fixture
def commands(monkeypatch):
    """Every 7-Zip command line run while the test is active."""
    seen = []
    real_popen, real_run = subprocess.Popen, subprocess.run

    def popen(args, **kw):
        seen.append(list(args))
        return real_popen(args, **kw)

    def run(args, **kw):
        seen.append(list(args))
        return real_run(args, **kw)
    monkeypatch.setattr(mp.subprocess, "Popen", popen)
    monkeypatch.setattr(mp.subprocess, "run", run)
    return seen


@needs_7zip
def test_s01_a_link_and_a_file_through_it_leave_nothing_outside_the_sandbox(tmp_path, commands):
    """S-01: a link to ../../../../.. and a file "written through it". The link is
    never requested; the file's bytes come back through the pipe into the
    sandbox; the other files of the image are still inspected (with `7z x`, 7-Zip
    refused the image and none of its members was looked at)."""
    p = _image(tmp_path / "crafted.dmg", [
        ("link", "link", "../../../../.."),
        ("link/escaped.txt", "file", MARKER),
        ("readme.txt", "file", b"hello"),
    ])
    sandboxes = []
    with ContainerExtractor().open(p) as res:
        sandboxes = list({Path(m.path).parents[1] for m in res.members if m.path})
        extracted = {m.name: Path(m.path).read_bytes() for m in res.members if m.extracted}
        assert extracted == {"crafted.dmg!/link/escaped.txt": MARKER,
                             "crafted.dmg!/readme.txt": b"hello"}
        assert all(str(Path(m.path)).startswith(str(sandboxes[0])) for m in res.members if m.path)
        assert _markers_outside(tmp_path, sandboxes) == []
        work = [d for d in sandboxes[0].iterdir() if d.name.startswith("img_")]
        assert work and all(not any(d.iterdir()) for d in work)   # 7-Zip wrote nothing
    assert _markers_outside(tmp_path, []) == []
    sevenzip = [c for c in commands if Path(c[0]).name.lower().startswith("7z")]
    assert sevenzip and {c[1] for c in sevenzip} == {"l", "e"}       # never "x"
    for c in sevenzip:
        if c[1] == "e":
            assert c[2:7] == ["-so", "-y", "-p", "-spd", "-bd"] and c[7] == "--"
            assert c[-1] != "link"                                     # links never requested


@needs_7zip
@pytest.mark.parametrize("name", ["../../escaped.txt", "/tmp/aegis_s01_abs.txt",
                                  "a/../../../escaped.txt", "-rf.txt", "*.txt"])
def test_traversal_absolute_and_switch_like_names_land_in_the_sandbox(tmp_path, name):
    p = _image(tmp_path / "names.dmg", [(name, "file", MARKER), ("ok.txt", "file", b"ok")])
    with ContainerExtractor().open(p) as res:
        roots = list({Path(m.path).parents[1] for m in res.members if m.path})
        got = sorted(Path(m.path).read_bytes() for m in res.members if m.extracted)
        assert got == sorted([MARKER, b"ok"])
        assert _markers_outside(tmp_path, roots) == []
    assert not Path("/tmp/aegis_s01_abs.txt").exists()


@needs_7zip
def test_the_byte_budget_is_enforced_while_streaming(tmp_path, monkeypatch):
    """A listing that under-states sizes passes the declared check; the stream is
    cut at the budget and nothing past it stays on disk."""
    p = _image(tmp_path / "liar.dmg", [("big.bin", "file", b"\x01" * 300_000)])
    real = mp.sevenzip_list

    def under_stated(tool, archive, *a, **k):
        items = real(tool, archive, *a, **k)
        for i in items:
            i.size = 10
        return items
    monkeypatch.setattr(ce, "sevenzip_list", under_stated)
    with ContainerExtractor(max_total_bytes=100_000).open(p) as res:
        assert not res.zip_bomb                           # as before: large, not a bomb
        assert any("not unpacked" in m.skipped_reason for m in res.members)
        assert res.total_uncompressed <= 100_000
        assert not any(m.extracted for m in res.members)


def _fake_popen(script):
    def popen(args, **kw):
        return subprocess.Popen([sys.executable, "-c", script], **kw)
    return popen


def test_a_member_that_hangs_is_killed_after_the_timeout(tmp_path):
    hang = _fake_popen("import time, sys; sys.stdout.write('x'); sys.stdout.flush(); time.sleep(60)")
    member = mp.SevenZipMember("7z", tmp_path / "i.dmg", "a", tmp_path, timeout=0.5, popen=hang)
    assert b"".join(member.chunks()) == b"x"
    assert member.close() is False and member.timed_out


def test_a_reader_that_stops_early_ends_the_process(tmp_path):
    endless = _fake_popen("import sys\nwhile True: sys.stdout.write('y' * 65536)")
    member = mp.SevenZipMember("7z", tmp_path / "i.dmg", "a", tmp_path, popen=endless)
    next(iter(member.chunks()))
    member.close()
    assert member.proc.poll() is not None


@pytest.mark.parametrize("script, expect", [
    ("import sys; sys.stdout.write('data')", b"data"),
    ("import sys; sys.stdout.write('data'); sys.exit(1)", b"data"),      # warnings
    ("import sys; sys.stdout.write('data'); sys.exit(2)", None),         # failure
    ("import sys; sys.stdout.write('d' * 5000)", None),                  # over the limit
])
def test_sevenzip_read(tmp_path, script, expect):
    assert mp.sevenzip_read("7z", tmp_path / "x", "m", tmp_path, 4096,
                            popen=_fake_popen(script)) == expect


@needs_7zip
def test_a_member_7zip_cannot_read_costs_only_that_member(tmp_path, monkeypatch):
    p = _image(tmp_path / "two.dmg", [("bad.txt", "file", b"bad"), ("good.txt", "file", b"good")])
    real = mp.SevenZipMember

    def member(tool, image, name, work, *a, **k):
        if name == "bad.txt":
            return real(tool, image, name, work, popen=_fake_popen("import sys; sys.exit(2)"))
        return real(tool, image, name, work, *a, **k)
    monkeypatch.setattr(ce, "SevenZipMember", member)
    with ContainerExtractor().open(p) as res:
        state = {m.name: (m.extracted, m.skipped_reason) for m in res.members}
    assert state == {"two.dmg!/bad.txt": (False, "7-Zip could not extract this file"),
                     "two.dmg!/good.txt": (True, "")}
    assert res.unreadable_members == 1


# ------------------------------------------------------------------ CHM, same model
def test_chm_pages_are_read_through_the_pipe(tmp_path, monkeypatch):
    page = (b'<html><object id=x classid="clsid:adb880a6-d8ff-11cf-9377-00aa003b7a11">'
            b'<param name="Command" value="ShortCut"></object></html>')
    listing = [mp.ListedItem("index.htm", len(page), False, False),
               mp.ListedItem("#SYSTEM", 8, False, False),
               mp.ListedItem("pics", 0, True, False),
               mp.ListedItem("evil", 0, False, True),
               mp.ListedItem("huge.exe", 10 ** 9, False, False),
               mp.ListedItem("broken.htm", 10, False, False)]
    asked = []

    def read(tool, archive, name, work, limit, *a, **k):
        asked.append(name)
        assert not any(work.iterdir())
        return page if name == "index.htm" else None
    monkeypatch.setattr(mp, "sevenzip_list", lambda tool, archive, *a, **k: listing)
    monkeypatch.setattr(mp, "sevenzip_read", read)
    p = tmp_path / "help.chm"
    p.write_bytes(b"ITSF" + b"\x00" * 200)
    with EmbeddedContentAnalyzer(sevenzip=lambda: "7z").open(p) as r:
        assert r.chm_shortcut and [m.name for m in r.members] == ["index.htm"]
        assert "huge.exe: too large" in r.skipped and "broken.htm: could not be read" in r.skipped
    assert asked == ["broken.htm", "index.htm"]          # links, folders, #/$ never asked
