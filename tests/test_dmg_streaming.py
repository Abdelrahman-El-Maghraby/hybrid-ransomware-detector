"""4.8 (S-01, PR-04, RF-4): disk-image members are streamed one at a time with
`7z e -so`, so 7-Zip never writes a file and its own path and link handling is
never relied on. Every image here is generated by the test (tests/macos_builder.py
wrapping a tar that 7-Zip reads as the partition): benign content with crafted
names and links, never a real sample."""

